/**
 * documentGenerator.ts
 * ─────────────────────────────────────────────────────────────────────────────
 * Generates a fact-checked lecture document in both .docx and .md formats.
 *
 * Uses the `docx` library (already in package.json) for Word export.
 * Falls back to Markdown download if docx fails.
 *
 * Document structure:
 *   • Title page (date, duration, participant count)
 *   • Executive summary (claim counts)
 *   • Corrections section (WRONG claims with Wikipedia corrections)
 *   • Uncertain claims (for manual review)
 *   • Verified facts
 *   • Full lecture transcript
 */

import type { DocumentData, FactClaim } from "@/hooks/useLectureFactCheck"
import type { Paragraph } from "docx"

// ── Markdown generator (always available, no deps) ────────────────────────────
function generateMarkdown(data: DocumentData, hostName: string): string {
    const date = new Date(data.generatedAt).toLocaleString()
    const correctClaims   = data.claims.filter(c => c.verdict === "CORRECT")
    const wrongClaims     = data.claims.filter(c => c.verdict === "WRONG")
    const uncertainClaims = data.claims.filter(c => c.verdict === "UNCERTAIN")

    const accuracyPct = data.claims.length > 0
        ? Math.round((correctClaims.length / data.claims.filter(c => c.verdict !== "PENDING" && c.verdict !== "CHECKING").length) * 100)
        : 0

    const lines: string[] = [
        "# 📚 Fact-Checked Lecture Document",
        "",
        `> **Lecturer:** ${hostName}  `,
        `> **Generated:** ${date}  `,
        `> **AI Accuracy Check:** ${accuracyPct}% of verified claims are correct  `,
        `> **Total Claims Detected:** ${data.claims.length}`,
        "",
        "---",
        "",
        "## 📊 Summary",
        "",
        `| Verdict | Count |`,
        `|---------|-------|`,
        `| ✅ Verified Correct | ${correctClaims.length} |`,
        `| ❌ Incorrect | ${wrongClaims.length} |`,
        `| ⚠️ Uncertain | ${uncertainClaims.length} |`,
        "",
    ]

    // Corrections section
    if (wrongClaims.length > 0) {
        lines.push("---")
        lines.push("")
        lines.push("## ❌ Corrections Required")
        lines.push("")
        lines.push("> The following statements made during the lecture appear to be **incorrect** based on Wikipedia.")
        lines.push("")
        wrongClaims.forEach((c, i) => {
            lines.push(`### Claim ${i + 1}: ${c.subject}`)
            lines.push("")
            lines.push(`**What was said:**`)
            lines.push(`> _"${c.rawSentence}"_`)
            lines.push("")
            if (c.correction) {
                lines.push(`**Correction (Wikipedia):**`)
                lines.push(`> ${c.correction}`)
                lines.push("")
            }
            if (c.wikiUrl) {
                lines.push(`📖 [Wikipedia Source](${c.wikiUrl})`)
                lines.push("")
            }
        })
    }

    // Uncertain claims
    if (uncertainClaims.length > 0) {
        lines.push("---")
        lines.push("")
        lines.push("## ⚠️ Claims Requiring Manual Verification")
        lines.push("")
        lines.push("> These statements could not be verified with high confidence. Please review manually.")
        lines.push("")
        uncertainClaims.forEach((c, i) => {
            lines.push(`${i + 1}. **${c.subject}** — _"${c.rawSentence.slice(0, 120)}…"_`)
            if (c.wikiUrl) lines.push(`   📖 [Wikipedia](${c.wikiUrl})`)
        })
        lines.push("")
    }

    // Verified facts
    if (correctClaims.length > 0) {
        lines.push("---")
        lines.push("")
        lines.push("## ✅ Verified Correct Statements")
        lines.push("")
        correctClaims.forEach((c, i) => {
            lines.push(`${i + 1}. **${c.subject}** — _"${c.rawSentence.slice(0, 120)}"_`)
        })
        lines.push("")
    }

    // Full transcript
    lines.push("---")
    lines.push("")
    lines.push("## 📝 Full Lecture Transcript")
    lines.push("")
    lines.push("```")
    lines.push(data.transcript || "(No transcript available)")
    lines.push("```")
    lines.push("")
    lines.push("---")
    lines.push("")
    lines.push("*Generated by Meet Clone AI · Fact-checked via Wikipedia · All analysis is on-device*")

    return lines.join("\n")
}

// ── DOCX generator ────────────────────────────────────────────────────────────
async function generateDocx(data: DocumentData, hostName: string): Promise<Blob | null> {
    try {
        const {
            Document, Packer, Paragraph, TextRun, HeadingLevel,
            AlignmentType, BorderStyle, TableCell, TableRow, Table,
            WidthType, ShadingType,
        } = await import("docx")

        const correctClaims   = data.claims.filter(c => c.verdict === "CORRECT")
        const wrongClaims     = data.claims.filter(c => c.verdict === "WRONG")
        const uncertainClaims = data.claims.filter(c => c.verdict === "UNCERTAIN")

        const children: Paragraph[] = []

        // ── Title ──────────────────────────────────────────────────────────────
        children.push(
            new Paragraph({
                children: [new TextRun({ text: "📚 Fact-Checked Lecture Document", bold: true, size: 36, color: "5B21B6" })],
                heading: HeadingLevel.TITLE,
                alignment: AlignmentType.CENTER,
            }),
            new Paragraph({
                children: [new TextRun({ text: `Lecturer: ${hostName}`, color: "6B7280", size: 22 })],
                alignment: AlignmentType.CENTER,
            }),
            new Paragraph({
                children: [new TextRun({ text: `Generated: ${new Date(data.generatedAt).toLocaleString()}`, color: "6B7280", size: 20 })],
                alignment: AlignmentType.CENTER,
            }),
            new Paragraph({ children: [new TextRun({ text: "" })] }),
        )

        // ── Summary table ──────────────────────────────────────────────────────
        children.push(
            new Paragraph({
                children: [new TextRun({ text: "📊 Summary", bold: true, size: 28, color: "1F2937" })],
                heading: HeadingLevel.HEADING_1,
            }),
        )

        const summaryRows = [
            ["Verdict", "Count"],
            ["✅ Verified Correct", String(correctClaims.length)],
            ["❌ Incorrect", String(wrongClaims.length)],
            ["⚠️ Uncertain", String(uncertainClaims.length)],
            ["Total Claims", String(data.claims.length)],
        ]

        const table = new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: summaryRows.map((row, ri) => new TableRow({
                children: row.map(cell => new TableCell({
                    children: [new Paragraph({
                        children: [new TextRun({ text: cell, bold: ri === 0, color: ri === 0 ? "FFFFFF" : "374151" })],
                    })],
                    shading: ri === 0
                        ? { type: ShadingType.SOLID, color: "5B21B6", fill: "5B21B6" }
                        : ri % 2 === 0 ? { type: ShadingType.SOLID, color: "F9FAFB", fill: "F9FAFB" } : undefined,
                })),
            })),
        })
        children.push(table as unknown as Paragraph)
        children.push(new Paragraph({ children: [new TextRun("")] }))

        // ── Corrections ────────────────────────────────────────────────────────
        if (wrongClaims.length > 0) {
            children.push(
                new Paragraph({
                    children: [new TextRun({ text: "❌ Corrections Required", bold: true, size: 28, color: "DC2626" })],
                    heading: HeadingLevel.HEADING_1,
                }),
                new Paragraph({
                    children: [new TextRun({ text: "The following statements appear incorrect based on Wikipedia.", italics: true, color: "6B7280" })],
                }),
                new Paragraph({ children: [new TextRun("")] }),
            )

            wrongClaims.forEach((c, i) => {
                children.push(
                    new Paragraph({
                        children: [new TextRun({ text: `Claim ${i + 1}: ${c.subject}`, bold: true, size: 24, color: "DC2626" })],
                        heading: HeadingLevel.HEADING_2,
                    }),
                    new Paragraph({
                        children: [
                            new TextRun({ text: "What was said: ", bold: true }),
                            new TextRun({ text: `"${c.rawSentence}"`, italics: true, color: "4B5563" }),
                        ],
                    }),
                )
                if (c.correction) {
                    children.push(
                        new Paragraph({
                            children: [
                                new TextRun({ text: "Correction: ", bold: true, color: "DC2626" }),
                                new TextRun({ text: c.correction, color: "374151" }),
                            ],
                        }),
                    )
                }
                if (c.wikiUrl) {
                    children.push(
                        new Paragraph({
                            children: [new TextRun({ text: `Source: ${c.wikiUrl}`, color: "2563EB" })],
                        }),
                    )
                }
                children.push(new Paragraph({ children: [new TextRun("")] }))
            })
        }

        // ── Uncertain ──────────────────────────────────────────────────────────
        if (uncertainClaims.length > 0) {
            children.push(
                new Paragraph({
                    children: [new TextRun({ text: "⚠️ Uncertain Claims (Manual Review)", bold: true, size: 28, color: "D97706" })],
                    heading: HeadingLevel.HEADING_1,
                }),
            )
            uncertainClaims.forEach((c, i) => {
                children.push(
                    new Paragraph({
                        children: [
                            new TextRun({ text: `${i + 1}. ${c.subject}: `, bold: true }),
                            new TextRun({ text: `"${c.rawSentence.slice(0, 150)}"`, italics: true, color: "6B7280" }),
                        ],
                    }),
                )
            })
            children.push(new Paragraph({ children: [new TextRun("")] }))
        }

        // ── Correct claims ─────────────────────────────────────────────────────
        if (correctClaims.length > 0) {
            children.push(
                new Paragraph({
                    children: [new TextRun({ text: "✅ Verified Correct Statements", bold: true, size: 28, color: "16A34A" })],
                    heading: HeadingLevel.HEADING_1,
                }),
            )
            correctClaims.forEach((c, i) => {
                children.push(
                    new Paragraph({
                        children: [
                            new TextRun({ text: `${i + 1}. ${c.subject}: `, bold: true }),
                            new TextRun({ text: `"${c.rawSentence.slice(0, 150)}"`, italics: true, color: "374151" }),
                        ],
                    }),
                )
            })
            children.push(new Paragraph({ children: [new TextRun("")] }))
        }

        // ── Transcript ─────────────────────────────────────────────────────────
        children.push(
            new Paragraph({
                children: [new TextRun({ text: "📝 Full Transcript", bold: true, size: 28, color: "1F2937" })],
                heading: HeadingLevel.HEADING_1,
            }),
        )

        const transcriptLines = (data.transcript || "No transcript").split("\n")
        transcriptLines.forEach(line => {
            children.push(
                new Paragraph({
                    children: [new TextRun({ text: line, font: "Courier New", size: 18, color: "374151" })],
                }),
            )
        })

        const doc = new Document({
            sections: [{ properties: {}, children }],
            creator: "Meet Clone AI",
            title: "Fact-Checked Lecture Document",
        })

        return await Packer.toBlob(doc)
    } catch (err) {
        console.warn("[documentGenerator] DOCX generation failed:", err)
        return null
    }
}

// ── Main export ───────────────────────────────────────────────────────────────
export async function downloadFactCheckedDocument(
    data: DocumentData,
    hostName: string,
    format: "docx" | "md" = "docx",
): Promise<void> {
    const ts   = new Date(data.generatedAt).toISOString().slice(0, 10)
    const base = `Lecture-FactCheck-${ts}`

    if (format === "docx") {
        const blob = await generateDocx(data, hostName)
        if (blob) {
            const url = URL.createObjectURL(blob)
            const a   = document.createElement("a")
            a.href     = url
            a.download = `${base}.docx`
            document.body.appendChild(a)
            a.click()
            URL.revokeObjectURL(url)
            document.body.removeChild(a)
            return
        }
        // Fallback to markdown
    }

    // Markdown fallback
    const md   = generateMarkdown(data, hostName)
    const blob = new Blob([md], { type: "text/markdown" })
    const url  = URL.createObjectURL(blob)
    const a    = document.createElement("a")
    a.href     = url
    a.download = `${base}.md`
    document.body.appendChild(a)
    a.click()
    URL.revokeObjectURL(url)
    document.body.removeChild(a)
}
